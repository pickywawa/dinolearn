def full(lang):
    t = L[lang]
    learn = list(t['learn'])
    if lang not in NO_VOICE and t['voice']:
        learn.append(t['voice'])
    safe = list(t['safe'])
    if lang not in NO_VOICE and t['mic']:
        safe.append(t['mic'])
    safe.append(t['offline'])
    bullets = lambda items: '\n'.join('• ' + i for i in items)
    return '\n\n'.join([
        t['intro'],
        t['h_learn'] + '\n' + bullets(learn),
        t['h_dino'] + '\n' + t['dino'],
        t['h_parents'] + '\n' + bullets(t['parents']),
        t['h_safe'] + '\n' + bullets(safe),
        t['langs'],
    ]) + '\n'

def main():
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'metadata', 'android')
    problems = []
    for lang, locales in LOCALES.items():
        t = L[lang]
        text = full(lang)
        for name, value, limit in [('title', t['title'], 30), ('short', t['short'], 80), ('full', text, 4000)]:
            if len(value) > limit:
                problems.append(f'{lang} {name}: {len(value)} > {limit}')
        for loc in locales:
            d = os.path.join(root, loc)
            os.makedirs(d, exist_ok=True)
            for f, v in [('title.txt', t['title']), ('short_description.txt', t['short']), ('full_description.txt', text)]:
                with open(os.path.join(d, f), 'w', encoding='utf-8') as fh:
                    fh.write(v.strip() + '\n')
        print(f'{lang:3} titre {len(t["title"]):2}  courte {len(t["short"]):2}  complète {len(text):4}  → {", ".join(locales)}')
    if problems:
        raise SystemExit('Trop long :\n' + '\n'.join(problems))

if __name__ == '__main__':
    main()
