/**
 * Devinettes et questions à voix haute (à partir de 5 ans), par thème.
 * L'enfant répond en parlant ; si le micro ne l'entend pas, il répond en
 * touchant la bonne carte. Les images `or-…` viennent de Noto (voir
 * scripts/build-icons.mjs), les autres sont celles des concepts et des pays.
 */

/** Carte de la réponse : une image, une forme, un nombre ou un mot écrit. */
export type OralCard = { image: string } | { shape: string } | { number: number } | { text: string };

export interface OralRiddle {
  /** Identifiant unique dans le thème. */
  id: string;
  level: number;
  text: string;
  /** Réponse avec son article (« le pompier ») : dite par le dino, acceptée avec ou sans article. */
  answer: string;
  /** Autres réponses acceptées (féminin, synonymes…). */
  also?: string[];
  card: OralCard;
  /** Réponses (identifiants) à ne pas proposer en cartes avec celle-ci : elles iraient aussi. */
  not?: string[];
  /** Indice, après une erreur. */
  hint?: string;
  /** Phrase après la bonne réponse (sinon « Oui ! C'est … ! »). */
  bravo?: string;
}

const img = (image: string): OralCard => ({ image });

